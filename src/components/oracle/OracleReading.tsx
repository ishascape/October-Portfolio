import { caseHref, sectionHref } from '../../links'
import { OracleCard } from './OracleCard'
import { CARD_BY_ID, CASE_STUDIES, type CardId } from './oracleData'
import type { OracleReading as Reading } from './oracleLogic'

type Props = {
  reading: Reading
  faces: boolean[]
  gather: boolean
  showSynthesis: boolean
  onOpen: (id: CardId) => void
}

const NOTES: Record<string, string> = {
  keyword: 'Matched to my eight areas by keyword. This reading is not generated by AI.',
  general: 'No close match, so this is my general approach. Matched by keyword, not generated by AI.',
}

// The three-card spread and the synthesis under it.
export function OracleReading({ reading, faces, gather, showSynthesis, onOpen }: Props) {
  const study = reading.caseStudyId ? CASE_STUDIES[reading.caseStudyId] : undefined
  const note = reading.mode ? NOTES[reading.mode] : undefined
  return (
    <>
      <ol className={`oracle__cards${gather ? ' is-gathering' : ''}`} aria-label="Your three-card reading">
        {reading.cards.map((c, i) => (
          <OracleCard
            key={i}
            index={i}
            card={CARD_BY_ID[c.cardId]}
            text={c.advice}
            role={c.role}
            faceUp={faces[i]}
            showProof
            onOpen={() => onOpen(c.cardId)}
          />
        ))}
      </ol>
      <div
        className={`oracle__synthesis${showSynthesis ? ' is-in' : ''}`}
        aria-hidden={showSynthesis ? undefined : true}
      >
        <h3 className="oracle__synthesis-title">The cards have spoken.</h3>
        <p>{reading.synthesis}</p>
        {note && <p className="oracle__note">{note}</p>}
        {study ? (
          <a className="oracle__link" href={caseHref(study.slug)}>
            See how I approached a similar problem <span aria-hidden="true">↗</span>
          </a>
        ) : (
          <a className="oracle__link" href={sectionHref('work', true)}>
            Explore my work <span aria-hidden="true">↗</span>
          </a>
        )}
      </div>
    </>
  )
}
